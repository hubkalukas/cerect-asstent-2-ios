import Foundation

enum SecretVault {
    // Obfuscated key bytes (no plaintext API key in source or binary)
    private static let encoded: [UInt8] = [
        0x1b, 0x30, 0x46, 0x2e, 0x14, 0x45, 0xd6, 0xc5, 0xa4, 0xd2,
        0x90, 0xe1, 0xe6, 0xf9, 0xfb, 0xee, 0xbe, 0xa4, 0x8b, 0xb0,
        0xb6, 0x97, 0x96, 0xd6, 0x77, 0x50, 0x77, 0x76, 0x41, 0x5d,
        0x63, 0x6c, 0x0a, 0x2a, 0x2f, 0x2b, 0x37, 0x30, 0x26, 0x0c,
        0x25, 0x3f, 0xd3, 0xc4, 0xcd, 0xdd, 0xcc, 0xec, 0xed, 0x83,
        0x80, 0x8f, 0x97
    ]

    static func defaultApiKey() -> String {
        var bytes = [UInt8](repeating: 0, count: encoded.count)
        for i in 0..<encoded.count {
            let mask = UInt8((0x5A + (i * 7)) & 0xFF)
            bytes[i] = encoded[i] ^ mask
        }
        return String(bytes: bytes, encoding: .utf8) ?? ""
    }
}
